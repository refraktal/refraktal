// Command release builds Refraktal's release assets: one archive per
// target, a SHA256SUMS file and the Homebrew formula. It is a maintainer
// script run by .github/workflows/release.yml, not part of the CLI.
//
//	go run ./scripts/release -version v0.1.0 -out dist
//
// Archives are deterministic: fixed timestamps, owners and order, and gzip
// without a name or time, so the same commit and Go version give the same
// bytes. Binaries are built with -trimpath, without cgo, and with the
// version stamped into refraktal.dev/refraktal.version.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"text/template"
	"time"
)

// Targets are the release platforms.
var Targets = []Target{{"darwin", "arm64"}, {"darwin", "amd64"}, {"linux", "arm64"}, {"linux", "amd64"}}

// Target is one GOOS/GOARCH pair.
type Target struct{ OS, Arch string }

// semver is the tag format releases use.
var semver = regexp.MustCompile(`^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$`)

// Archive is the asset name for a target: refraktal_<version without v>_<os>_<arch>.tar.gz.
func Archive(version string, t Target) string {
	return fmt.Sprintf("refraktal_%s_%s_%s.tar.gz", strings.TrimPrefix(version, "v"), t.OS, t.Arch)
}

// epoch is the archive timestamp: fixed, so archives are reproducible.
var epoch = time.Unix(0, 0).UTC()

// pack writes a deterministic tar.gz holding the given files, in order.
func pack(w io.Writer, files []packed) error {
	gz, err := gzip.NewWriterLevel(w, gzip.BestCompression)
	if err != nil {
		return err
	}
	gz.ModTime, gz.Name, gz.OS = time.Time{}, "", 255
	tw := tar.NewWriter(gz)
	for _, f := range files {
		h := &tar.Header{Name: f.name, Mode: f.mode, Size: int64(len(f.data)), ModTime: epoch, Typeflag: tar.TypeReg,
			Uid: 0, Gid: 0, Uname: "", Gname: "", Format: tar.FormatPAX}
		if err := tw.WriteHeader(h); err != nil {
			return err
		}
		if _, err := tw.Write(f.data); err != nil {
			return err
		}
	}
	if err := tw.Close(); err != nil {
		return err
	}
	return gz.Close()
}

type packed struct {
	name string
	mode int64
	data []byte
}

// Sums renders a SHA256SUMS file (sha256sum format) for name -> bytes.
func Sums(files map[string][]byte) string {
	var names []string
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	for _, n := range names {
		h := sha256.Sum256(files[n])
		fmt.Fprintf(&b, "%s  %s\n", hex.EncodeToString(h[:]), n)
	}
	return b.String()
}

// formula is the Homebrew formula for the tap (refraktal/homebrew-tap).
var formula = template.Must(template.New("formula").Parse(`# Generated by scripts/release for {{.Version}}. Do not edit by hand.
class Refraktal < Formula
  desc "Meta-harness: one prompt in, a spectrum of coding agents out"
  homepage "https://refraktal.dev"
  version "{{.Bare}}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "{{.URL}}/{{index .Assets "darwin_arm64"}}"
      sha256 "{{index .Sums "darwin_arm64"}}"
    end
    on_intel do
      url "{{.URL}}/{{index .Assets "darwin_amd64"}}"
      sha256 "{{index .Sums "darwin_amd64"}}"
    end
  end

  on_linux do
    on_arm do
      url "{{.URL}}/{{index .Assets "linux_arm64"}}"
      sha256 "{{index .Sums "linux_arm64"}}"
    end
    on_intel do
      url "{{.URL}}/{{index .Assets "linux_amd64"}}"
      sha256 "{{index .Sums "linux_amd64"}}"
    end
  end

  def install
    bin.install "refraktal"
  end

  test do
    assert_match "usage: refraktal", shell_output("#{bin}/refraktal --help")
  end
end
`))

// Formula renders the Homebrew formula from the archives' bytes.
func Formula(version string, archives map[Target][]byte) (string, error) {
	data := struct {
		Version, Bare, URL string
		Assets, Sums       map[string]string
	}{version, strings.TrimPrefix(version, "v"), "https://github.com/refraktal/refraktal/releases/download/" + version,
		map[string]string{}, map[string]string{}}
	for _, t := range Targets {
		b, ok := archives[t]
		if !ok {
			return "", fmt.Errorf("no archive for %s/%s", t.OS, t.Arch)
		}
		key := t.OS + "_" + t.Arch
		h := sha256.Sum256(b)
		data.Assets[key], data.Sums[key] = Archive(version, t), hex.EncodeToString(h[:])
	}
	var out bytes.Buffer
	err := formula.Execute(&out, data)
	return out.String(), err
}

func build(version, out string, t Target) ([]byte, error) {
	bin := filepath.Join(out, "build", t.OS+"_"+t.Arch, "refraktal")
	cmd := exec.Command("go", "build", "-trimpath", "-ldflags", "-s -w -buildid= -X refraktal.dev/refraktal.version="+version,
		"-o", bin, "./cmd/refraktal")
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS="+t.OS, "GOARCH="+t.Arch)
	cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("build %s/%s: %w", t.OS, t.Arch, err)
	}
	return os.ReadFile(bin)
}

func main() {
	version := flag.String("version", "", "release version, a semver tag such as v0.1.0")
	out := flag.String("out", "dist", "output folder (must not exist yet)")
	flag.Parse()
	if !semver.MatchString(*version) {
		fmt.Fprintf(os.Stderr, "release: -version %q is not a semver tag like v0.1.0\n", *version)
		os.Exit(2)
	}
	if _, err := os.Stat(*out); err == nil {
		fmt.Fprintf(os.Stderr, "release: %s exists; remove it first\n", *out)
		os.Exit(2)
	}
	if err := run(*version, *out); err != nil {
		fmt.Fprintln(os.Stderr, "release:", err)
		os.Exit(1)
	}
}

func run(version, out string) error {
	license, err := os.ReadFile("LICENSE")
	if err != nil {
		return err
	}
	readme, err := os.ReadFile("README.md")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	archives := map[Target][]byte{}
	files := map[string][]byte{}
	for _, t := range Targets {
		bin, err := build(version, out, t)
		if err != nil {
			return err
		}
		var buf bytes.Buffer
		if err := pack(&buf, []packed{{"refraktal", 0o755, bin}, {"LICENSE", 0o644, license}, {"README.md", 0o644, readme}}); err != nil {
			return err
		}
		archives[t], files[Archive(version, t)] = buf.Bytes(), buf.Bytes()
		if err := os.WriteFile(filepath.Join(out, Archive(version, t)), buf.Bytes(), 0o644); err != nil {
			return err
		}
	}
	if err := os.RemoveAll(filepath.Join(out, "build")); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(out, "SHA256SUMS"), []byte(Sums(files)), 0o644); err != nil {
		return err
	}
	f, err := Formula(version, archives)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(out, "refraktal.rb"), []byte(f), 0o644); err != nil {
		return err
	}
	fmt.Printf("release %s: %d archives, SHA256SUMS and refraktal.rb in %s\n", version, len(archives), out)
	return nil
}
